from __future__ import annotations

import argparse
import base64
import hashlib
import json
import subprocess
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK_PATH = REPO_ROOT / "notebooks" / "yolo11m_grouped_oof.ipynb"
KERNEL_DIR = REPO_ROOT / "artifacts" / "kaggle" / "yolo11m-grouped-oof"
KERNEL_ID = "mrinanksivakumar/equinexus-yolo11m-grouped-oof"
RUN_NAME = "yolo11m-seg-1024-20ep-coco-oof"


def _cell(cell_type: str, source: str) -> dict[str, Any]:
    result: dict[str, Any] = {
        "id": hashlib.sha1(f"{cell_type}\0{source}".encode("utf-8")).hexdigest()[:8],
        "cell_type": cell_type,
        "metadata": {},
        "source": source.splitlines(keepends=True),
    }
    if cell_type == "code":
        result.update(execution_count=None, outputs=[])
    return result


def _source_files() -> list[Path]:
    return [
        *sorted((REPO_ROOT / "src" / "filament_baseline").glob("*.py")),
        REPO_ROOT / "scripts" / "export_yolo_dataset.py",
        REPO_ROOT / "scripts" / "run_yolo_detector_experiment.py",
        REPO_ROOT / "scripts" / "run_yolo_training_partition_oof.py",
        REPO_ROOT / "scripts" / "score_yolo_oof.py",
        REPO_ROOT / "configs" / "validation-baseline.json",
        REPO_ROOT / "data" / "splits" / "observation_oof_seed42_5fold.csv",
        REPO_ROOT / "requirements-detector.txt",
    ]


def _bundle(paths: list[Path]) -> tuple[dict[str, str], str]:
    encoded: dict[str, str] = {}
    digest = hashlib.sha256()
    for path in paths:
        if not path.is_file():
            raise FileNotFoundError(path)
        relative = path.relative_to(REPO_ROOT).as_posix()
        content = path.read_bytes()
        encoded[relative] = base64.b64encode(content).decode("ascii")
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(content)
        digest.update(b"\0")
    return encoded, digest.hexdigest()


def build() -> tuple[Path, Path]:
    source_files = _source_files()
    encoded, source_bundle_sha256 = _bundle(source_files)
    oof_manifest_path = REPO_ROOT / "data" / "splits" / "observation_oof_seed42_5fold.csv"
    oof_manifest_sha256 = hashlib.sha256(oof_manifest_path.read_bytes()).hexdigest()
    source_commit = subprocess.run(
        ["git", "-C", str(REPO_ROOT), "rev-parse", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    markdown = f"""# EquiNexus YOLO11m grouped OOF experiment

Train five observation-grouped YOLO11m-seg folds on the 565-observation training partition. Every prediction is generated by a fold that did not train on that observation; the frozen 142-observation holdout is excluded from this experiment. The model uses public COCO-pretrained weights under AGPL-3.0 and only competition-provided training annotations. No test images or labels are used for training or validation.

Configuration: 1024-pixel input, 20 epochs, batch size 2, five folds, one Kaggle GPU. OOF manifest SHA-256: `{oof_manifest_sha256}`. The run and fold artifacts are written under `/kaggle/working/equinexus/{RUN_NAME}`. Compare these predictions with the existing YOLO11s OOF predictions using the same grouped scorer and frozen OOF manifest.
"""
    source_cell = (
        "import base64\n"
        "from pathlib import Path\n"
        "REPOSITORY_PATH = Path('/kaggle/working/EquiNexus')\n"
        f"SOURCE_COMMIT = {source_commit!r}\n"
        f"SOURCE_BUNDLE_SHA256 = {source_bundle_sha256!r}\n"
        f"SOURCE_FILES = {json.dumps(encoded, separators=(',', ':'))}\n"
        "for relative, payload in SOURCE_FILES.items():\n"
        "    destination = REPOSITORY_PATH / relative\n"
        "    destination.parent.mkdir(parents=True, exist_ok=True)\n"
        "    destination.write_bytes(base64.b64decode(payload))\n"
        "print({'source_commit': SOURCE_COMMIT, 'source_bundle_sha256': SOURCE_BUNDLE_SHA256, 'files': len(SOURCE_FILES)})\n"
    )
    runtime_cell = (
        "import os, subprocess, sys\n"
        "os.environ['EQUINEXUS_SOURCE_COMMIT'] = SOURCE_COMMIT\n"
        "os.environ['EQUINEXUS_SOURCE_BUNDLE_SHA256'] = SOURCE_BUNDLE_SHA256\n"
        "os.environ['YOLO_CONFIG_DIR'] = '/kaggle/working/equinexus/yolo11m-config'\n"
        "os.environ['TORCH_HOME'] = '/kaggle/working/equinexus/torch-home'\n"
        "Path(os.environ['YOLO_CONFIG_DIR']).mkdir(parents=True, exist_ok=True)\n"
        "Path(os.environ['TORCH_HOME']).mkdir(parents=True, exist_ok=True)\n"
        "subprocess.run([sys.executable, '-m', 'pip', 'install', '--disable-pip-version-check', '--no-cache-dir', '-r', str(REPOSITORY_PATH / 'requirements-detector.txt')], check=True)\n"
        "import torch, ultralytics\n"
        "devices = [{'name': torch.cuda.get_device_name(i), 'total_memory_bytes': torch.cuda.get_device_properties(i).total_memory} for i in range(torch.cuda.device_count())]\n"
        "print({'python': sys.version.split()[0], 'torch': torch.__version__, 'cuda': torch.version.cuda, 'ultralytics': ultralytics.__version__, 'devices': devices})\n"
        "assert torch.cuda.is_available(), 'A Kaggle GPU is required for this run'\n"
    )
    run_cell = (
        "command = [sys.executable, '-u', str(REPOSITORY_PATH / 'scripts' / 'run_yolo_training_partition_oof.py'), "
        "'--repo-root', str(REPOSITORY_PATH), '--run-name', "
        f"{RUN_NAME!r}, '--folds', '5', '--model', 'yolo11m-seg.pt', '--image-size', '1024', "
        "'--epochs', '20', '--batch-size', '2', '--workers', '4', '--patience', '7', '--device', '0', "
        "'--fraction', '1.0', '--mask-ratio', '2', '--prediction-confidence', '0.05', '--nms-iou', '0.6', '--max-detections', '150']\n"
        "print('Starting five-fold YOLO11m training:', ' '.join(command), flush=True)\n"
        "subprocess.run(command, check=True)\n"
    )
    report_cell = (
        "import json\n"
        f"run_root = Path('/kaggle/working/equinexus/{RUN_NAME}')\n"
        "metadata_path = run_root / 'run-metadata.json'\n"
        "print('run metadata:', metadata_path, 'exists=', metadata_path.is_file())\n"
        "if metadata_path.is_file(): print(json.dumps(json.loads(metadata_path.read_text()), indent=2))\n"
        "print('OOF detections:', (run_root / 'oof_detections.json').stat().st_size if (run_root / 'oof_detections.json').is_file() else 'pending')\n"
    )
    notebook = {
        "cells": [
            _cell("markdown", markdown),
            _cell("code", source_cell),
            _cell("code", runtime_cell),
            _cell("code", run_cell),
            _cell("code", report_cell),
        ],
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.13.0"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    NOTEBOOK_PATH.parent.mkdir(parents=True, exist_ok=True)
    NOTEBOOK_PATH.write_text(json.dumps(notebook, indent=1) + "\n", encoding="utf-8")
    KERNEL_DIR.mkdir(parents=True, exist_ok=True)
    (KERNEL_DIR / NOTEBOOK_PATH.name).write_bytes(NOTEBOOK_PATH.read_bytes())
    metadata = {
        "id": KERNEL_ID,
        "title": "EquiNexus YOLO11m Grouped OOF",
        "code_file": NOTEBOOK_PATH.name,
        "language": "python",
        "kernel_type": "notebook",
        "is_private": "true",
        "enable_gpu": "true",
        "enable_internet": "true",
        "machine_shape": "",
        "dataset_sources": [],
        "competition_sources": ["filament-segmentation-2026"],
        "kernel_sources": [],
        "model_sources": [],
    }
    metadata_path = KERNEL_DIR / "kernel-metadata.json"
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(f"Notebook: {NOTEBOOK_PATH}")
    print(f"Kaggle bundle: {KERNEL_DIR}")
    print(f"Source bundle SHA-256: {source_bundle_sha256}")
    return NOTEBOOK_PATH, metadata_path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build the five-fold Kaggle YOLO11m OOF notebook.")
    parser.parse_args()
    build()
